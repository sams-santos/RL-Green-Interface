"""Write data/reference.js: TSPLIB instances, carbon intensity per country and everyday equivalents.

Sources:
* data/instances/*.tsp, *.atsp - TSPLIB files (coordinates are kept for drawing paths)
* data/global_energy_mix.json  - {ISO3: {country_name, iso_alpha2, carbon_intensity, year}},
  carbon_intensity in g CO2eq/kWh. Countries without a carbon intensity are ignored.
* data/equivalents.json        - everyday comparisons: energy (kWh) or CO2eq (kg) per unit,
  with the value as published and its source.

Run it again after changing any source:  python tools/build_reference.py
"""
import json
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"
INSTANCE_DIR = DATA / "instances"

# Known optimal tour lengths (TSPLIB95). Instances not listed simply show no optimum.
OPTIMA = {"eil51": 426, "berlin52": 7542, "st70": 675, "kroA100": 21282, "tsp225": 3916,
          "br17": 39, "ftv33": 1286, "ftv64": 1839}


def parse_tsplib(path):
    header, section, body = {}, None, []
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if not line or line == "EOF":
            continue
        if section is None and ":" in line:
            key, value = line.split(":", 1)
            header[key.strip().upper()] = value.strip()
        elif line.endswith("_SECTION"):
            section = line
        else:
            body.extend(line.split())
    n = int(header["DIMENSION"])
    coords = None
    if section == "NODE_COORD_SECTION":
        values = [float(v) for v in body]
        coords = [[round(values[i * 3 + 1], 2), round(values[i * 3 + 2], 2)] for i in range(n)]
    return {"type": header["TYPE"].upper(), "dimension": n, "optimum": OPTIMA.get(path.stem), "coords": coords}


def instances():
    """{name: info} for every instance file, TSP first then ATSP, each by size."""
    found = {path.stem: parse_tsplib(path)
             for path in list(INSTANCE_DIR.glob("*.tsp")) + list(INSTANCE_DIR.glob("*.atsp"))}
    return dict(sorted(found.items(), key=lambda kv: (kv[1]["type"] != "TSP", kv[1]["dimension"])))


def countries():
    mix = json.loads((DATA / "global_energy_mix.json").read_text(encoding="utf-8"))
    rows = [{"iso": iso3, "flag": (row.get("iso_alpha2") or "").lower() or None, "name": row["country_name"],
             "intensity": row["carbon_intensity"], "year": row.get("year")}
            for iso3, row in mix.items() if (row.get("carbon_intensity") or 0) > 0]
    return sorted(rows, key=lambda c: c["name"])


def main():
    equivalents = json.loads((DATA / "equivalents.json").read_text(encoding="utf-8"))
    reference = {"instances": instances(), "countries": countries(), "equivalents": equivalents}
    (DATA / "reference.js").write_text(
        "// Generated by tools/build_reference.py from data/instances, global_energy_mix.json and equivalents.json. Do not edit by hand.\n"
        "window.GREEN_RL_REFERENCE = " + json.dumps(reference, separators=(",", ":"), ensure_ascii=False) + ";\n",
        encoding="utf-8")
    print(f"Wrote data/reference.js: {len(reference['instances'])} instances, {len(reference['countries'])} countries, "
          f"{len(equivalents['equivalents'])} equivalents")


if __name__ == "__main__":
    main()
