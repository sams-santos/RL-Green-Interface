"""Write data/world.js: country shapes for the emissions map.

Source: Natural Earth admin-0 countries (public domain), https://www.naturalearthdata.com/
* 1:110m polygons are drawn as the map.
* Countries in data/global_energy_mix.json that are too small for 1:110m are drawn as dots, placed
  at their 1:50m label point (or at FALLBACK_POINTS for territories Natural Earth merges into France
  or the UK).

Run once, or after changing data/global_energy_mix.json:  python tools/build_world.py
"""
import json
import urllib.request
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"
BASE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/"
DROP = {"ATA"}  # Antarctica: no grid, and it takes a third of the map
FALLBACK_POINTS = {  # lon, lat
    "GIB": (-5.35, 36.14), "GLP": (-61.55, 16.25), "GUF": (-53.1, 3.9),
    "MTQ": (-61.02, 14.64), "REU": (55.53, -21.13),
}


def fetch(name):
    with urllib.request.urlopen(BASE + name) as response:
        return json.load(response)["features"]


def iso3(props):
    for key in ("ISO_A3_EH", "ISO_A3", "ADM0_A3"):
        code = props.get(key)
        if code and code != "-99":
            return code
    return None


def ring(points, clockwise):
    """Round to 0.01°, drop repeated points and orient the ring the way d3-geo expects
    (exterior rings clockwise, holes anticlockwise)."""
    out = []
    for lon, lat in points:
        p = [round(lon, 2), round(lat, 2)]
        if not out or out[-1] != p:
            out.append(p)
    if len(out) < 4:
        return None
    area = sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(out, out[1:]))
    if (area < 0) != clockwise:
        out.reverse()
    return out


def polygons(geometry):
    polys = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    result = []
    for poly in polys:
        rings = [ring(r, k == 0) for k, r in enumerate(poly)]
        if rings[0]:
            result.append([r for r in rings if r])
    return result


def main():
    known = json.loads((DATA / "global_energy_mix.json").read_text(encoding="utf-8"))
    shapes = []
    for feature in fetch("ne_110m_admin_0_countries.geojson"):
        props = feature["properties"]
        code = iso3(props)
        if code in DROP:
            continue
        shapes.append({"iso": code, "name": props["NAME"], "polygons": polygons(feature["geometry"])})
    drawn = {s["iso"] for s in shapes}

    labels = {iso3(f["properties"]): (f["properties"]["LABEL_X"], f["properties"]["LABEL_Y"])
              for f in fetch("ne_50m_admin_0_countries.geojson")}
    labels.update(FALLBACK_POINTS)
    points = [{"iso": code, "lon": round(labels[code][0], 2), "lat": round(labels[code][1], 2)}
              for code in sorted(known) if code not in drawn and code in labels]
    missing = sorted(code for code in known if code not in drawn and code not in labels)

    (DATA / "world.js").write_text(
        "// Generated by tools/build_world.py from Natural Earth admin-0 countries (public domain). Do not edit by hand.\n"
        "window.GREEN_RL_WORLD = " + json.dumps({"shapes": shapes, "points": points}, separators=(",", ":"),
                                                ensure_ascii=False) + ";\n",
        encoding="utf-8")
    print(f"Wrote data/world.js: {len(shapes)} shapes, {len(points)} dots"
          + (f"; not placed: {', '.join(missing)}" if missing else ""))


if __name__ == "__main__":
    main()
