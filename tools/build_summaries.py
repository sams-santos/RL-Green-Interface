"""Write data/summaries/<instance>.js: the best distance and total energy of every run on one
instance, for the ECOVIS score (js/scores.js), which rates a run against all runs on its instance.

Reads the shards written by tools/build_dataset.py (data/runs/) and data/manifest.js. Values are
stored in the order of the manifest grid (algorithm, reward, epsilon_decay, epsilon_init, gamma,
alpha, seed), with null for a combination that has no run. build_dataset.py runs this at the end.

Usage:
    python tools/build_summaries.py
"""
import itertools
import json
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"
ORDER = ["algorithm", "reward", "epsilon_decay", "epsilon_init", "gamma", "alpha", "seed"]


def read_js(path, prefix):
    text = path.read_text(encoding="utf-8")
    start = text.index(prefix) + len(prefix)
    return json.loads(text[start:text.rindex(")" if prefix.endswith("(") else ";")])


def key(value):
    return round(value, 6) if isinstance(value, float) else value


def main():
    manifest = read_js(DATA / "manifest.js", "window.GREEN_RL_MANIFEST = ")
    grid = manifest["grid"]
    index = {combo: k for k, combo in enumerate(itertools.product(*[[key(v) for v in grid[name]] for name in ORDER]))}
    out = DATA / "summaries"
    out.mkdir(exist_ok=True)
    for old in out.glob("*.js"):
        old.unlink()

    for instance in grid["instance"]:
        best, energy = [None] * len(index), [None] * len(index)
        for path in sorted((DATA / "runs").glob(f"*/{instance}/*.js")):
            shard = read_js(path, "GreenRL.registerShard(")
            for run in shard["runs"]:
                combo = tuple(key(v) for v in (shard["algorithm"], shard["reward"], shard["epsilon_decay"],
                                                shard["epsilon_init"], run["gamma"], run["alpha"], shard["seed"]))
                k = index[combo]
                best[k] = int(run["summary"]["best"])
                energy[k] = float(f"{run['summary']['energy']:.4g}")
        payload = {"instance": instance, "order": ORDER, "best": best, "energy": energy}
        (out / f"{instance}.js").write_text(
            "// Generated by tools/build_summaries.py. Do not edit by hand.\n"
            "GreenRLScores.registerSummaries(" + json.dumps(payload, separators=(",", ":")) + ");\n", encoding="utf-8")
        print(f"  {instance}: {sum(b is not None for b in best):,} runs")
    print(f"Wrote data/summaries/ ({sum(p.stat().st_size for p in out.glob('*.js')) / 1e3:.0f} kB)")


if __name__ == "__main__":
    main()
