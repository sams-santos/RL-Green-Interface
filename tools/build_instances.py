"""Write data/instances.js (node coordinates and metadata) from the TSPLIB files in data/instances.

Run it again after adding or removing an instance file.

Usage:  python tools/build_instances.py
"""
import json
from pathlib import Path

from tsplib_utils import instance_files, read_instance

OUT = Path(__file__).resolve().parent.parent / "data" / "instances.js"


def main():
    instances = {}
    for name in instance_files():
        inst = read_instance(name)
        instances[name] = {
            "type": inst["type"],
            "dimension": inst["dimension"],
            "optimum": inst["optimum"],
            "coords": [[round(x, 2), round(y, 2)] for x, y in inst["coords"]] if inst["coords"] else None,
        }
    OUT.write_text(
        "// Generated by tools/build_instances.py from TSPLIB95. Do not edit by hand.\n"
        "window.GREEN_RL_INSTANCES = " + json.dumps(instances, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
